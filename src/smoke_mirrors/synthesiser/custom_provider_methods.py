    def residents(self) -> int:
        min_val = 1
        max_val = 12
        spread = 0.25
        shift = -0.8

        return int(math_gauss(min_val, max_val, 0, spread, shift))

    def children(self) -> int:
        min_val = 1
        max_val = 12
        spread = 0.25
        shift = -1.2

        log_min = math.log(min_val)
        log_max = math.log(max_val)
        log_range = log_max - log_min

        log_mid = (log_min + log_max) / 2 + (shift * log_range / 4)
        log_sigma = log_range * spread / 2

        z = random.gauss(log_mid, log_sigma)
        return_val = math.exp(z)

        if return_val < min_val:
            return_val = min_val
        elif return_val > max_val:
            return_val = max_val

        return int(return_val)

    def rent(self) -> float:
        min_val = 50
        max_val = 5000
        spread = 0.3
        round_to = 2
        shift = -0.4

        return math_gauss(min_val, max_val, round_to, spread, shift)

