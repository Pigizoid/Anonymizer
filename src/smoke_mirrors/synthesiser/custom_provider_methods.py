    def bitcoin(self) -> str:
        private_key = random.randbytes(32)
        public_key = sha256(private_key)

        pubkey_hash = ripemd160(sha256(public_key))

        versioned_payload = b"\x00" + pubkey_hash

        checksum = sha256(sha256(versioned_payload))[:4]

        address_bytes = versioned_payload + checksum
        address = base58_encode(address_bytes)

        return address

